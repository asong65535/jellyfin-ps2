#!/usr/bin/env python3
"""
Turn assets/logo.png into src/logo_data.c, pixelated to match the font.

The font is a pixel typeface drawn at whole-number scales, so a smooth
anti-aliased logo next to it looks wrong. Three steps fix that:

  1. downscale to a coarse grid, averaging properly on the way down
  2. posterise the colours and harden the alpha, so no soft gradients
     or semi-transparent edges survive
  3. upscale by a whole number with nearest-neighbour, which makes every
     logo pixel a visible PIXEL_SIZE-by-PIXEL_SIZE block

PIXEL_SIZE 2 matches the wordmark, which is drawn at scale 2.0. Raise it
for a chunkier look.

Hard alpha also avoids fringing: the GS blends semi-transparent pixels
against transparent black and leaves dark halos on analog output.

Missing file is not an error. logo_width comes out 0 and the splash falls
back to the wordmark alone.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC  = os.path.join(ROOT, "assets", "logo.png")
OUT  = os.path.join(ROOT, "src", "logo_data.c")
PREVIEW = os.path.join(ROOT, "tools", "logo_preview.png")

MAX_DIM        = 128    # final on-screen size in pixels
PIXEL_SIZE     = 2      # one logo pixel = this many screen pixels
POSTERIZE_BITS = 3      # per channel: 3 gives 8 levels, 2 gives 4
ALPHA_CUT      = 110    # at or above this becomes opaque, below transparent

# When the source has no transparency at all, which is the case for any JPEG
# or a flattened PNG, anything close to the corner colour is keyed out. For
# the Jellyfin mark that is exactly right: the dark areas inside the
# triangle are meant to be background, not part of the shape.
BG_KEY_TOL     = 120    # sum of per-channel differences. 0 disables keying


def csm1_slot(i):
    """Where palette entry i is stored in an 8-bit CLUT laid out the GS's
    default way (CSM1): bits 3 and 4 of the index are swapped."""
    return (i & 0xE7) | ((i & 0x08) << 1) | ((i & 0x10) >> 1)


def write(w, h, index=b"", palette=()):
    """An 8-bit palette image: one index byte per pixel, and 256 colours
    as ABGR words (the GS's CT32), already in CSM1 order, entry 0 being
    transparent. 64 KB of VRAM becomes 17."""
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/genlogo.py. Do not edit. */\n")
        f.write('#include "logo.h"\n\n')
        f.write(f"const int logo_width  = {w};\n")
        f.write(f"const int logo_height = {h};\n\n")

        if w == 0:
            f.write("const unsigned char logo_index[] = { 0 };\n")
            f.write("const unsigned int  logo_clut[256] = { 0 };\n")
            return

        clut = [0] * 256
        for i, (r, g, b, a) in enumerate(palette):
            clut[csm1_slot(i)] = (a << 24) | (b << 16) | (g << 8) | r

        f.write("/* One palette index per pixel; 0 is transparent. */\n")
        f.write("const unsigned char logo_index[] = {\n")
        for i in range(0, len(index), 32):
            f.write("\t" + ",".join(str(b) for b in index[i:i + 32]) + ",\n")
        f.write("};\n\n")

        f.write("/* 256 ABGR colours in CSM1 order (see csm1_slot);   */\n"
                "/* alpha is 0x80 for opaque, the GS's range.          */\n")
        f.write("const unsigned int logo_clut[256] = {\n")
        for i in range(0, 256, 8):
            f.write("\t" + ",".join("0x%08X" % c for c in clut[i:i + 8]) + ",\n")
        f.write("};\n")


def main():
    if not os.path.exists(SRC):
        print("no assets/logo.png, splash will use the wordmark only")
        write(0, 0)
        return

    from PIL import Image, ImageOps

    im = Image.open(SRC).convert("RGBA")

    # 0. key the background out if the source has none of its own.
    lo, hi = im.getchannel("A").getextrema()
    if BG_KEY_TOL > 0 and lo == 255 and hi == 255:
        px = im.load()
        kr, kg, kb, _ = px[1, 1]
        w0, h0 = im.size

        for y in range(h0):
            for x in range(w0):
                r, g, b, _a = px[x, y]
                if abs(r - kr) + abs(g - kg) + abs(b - kb) < BG_KEY_TOL:
                    px[x, y] = (0, 0, 0, 0)

        print(f"source was fully opaque, keyed out "
              f"rgb({kr},{kg},{kb}) and near neighbours")

    # 1. down to the coarse grid. LANCZOS so detail averages rather than
    #    dropping out, which matters at these sizes.
    small = max(1, MAX_DIM // PIXEL_SIZE)
    im.thumbnail((small, small), Image.LANCZOS)

    # 2. flatten the palette and harden the edges.
    rgb, alpha = im.convert("RGB"), im.getchannel("A")
    rgb   = ImageOps.posterize(rgb, POSTERIZE_BITS)
    alpha = alpha.point(lambda a: 255 if a >= ALPHA_CUT else 0)
    im    = Image.merge("RGBA", (*rgb.split(), alpha))

    # 3. back up by a whole factor, nearest so the blocks stay square.
    gw, gh = im.size
    im = im.resize((gw * PIXEL_SIZE, gh * PIXEL_SIZE), Image.NEAREST)
    w, h = im.size

    # Preview on a dark ground, since transparent looks blank in viewers.
    bg = Image.new("RGBA", (w, h), (16, 18, 42, 255))
    bg.alpha_composite(im)
    bg.save(PREVIEW)

    # Palette: entry 0 transparent, then each opaque colour once. The
    # posterised logo has few colours; should it ever have more than 255,
    # the opaque part is reduced to 255 first.
    opaque = im.convert("RGB")
    mask = im.getchannel("A")

    def pixels():
        op, mk = opaque.load(), mask.load()
        return [(op[x, y], mk[x, y]) for y in range(h) for x in range(w)]

    colours = {c for c, a in pixels() if a}

    if len(colours) > 255:
        opaque = opaque.quantize(255).convert("RGB")
        colours = {c for c, a in pixels() if a}

    palette = [(0, 0, 0, 0)] + [(r, g, b, 0x80) for r, g, b in sorted(colours)]
    slot = {c[:3]: i for i, c in enumerate(palette) if i}

    index = bytearray(slot[c] if a else 0 for c, a in pixels())

    write(w, h, index, palette)

    print(f"logo {w}x{h} from a {gw}x{gh} grid at {PIXEL_SIZE}x, "
          f"{len(palette) - 1} colours, 8-bit palette")
    print("preview -> tools/logo_preview.png")


if __name__ == "__main__":
    main()
